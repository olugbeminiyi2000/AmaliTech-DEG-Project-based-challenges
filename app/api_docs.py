# HTTP header values always arrive as text, so the endpoint receives them as
# strings and parses them itself (see validation.py and simulation.py). These
# schemas only change how /docs presents them: a plain string field, a number
# field and a true/false dropdown.
HEADER_SCHEMAS = {
    "Idempotency-Key": {"type": "string", "maxLength": 255},
    "X-Simulate-Bank-Delay": {"type": "number", "minimum": 0, "maximum": 30},
    "X-Simulate-Bank-Failure": {"type": "boolean"},
}


def apply_header_schemas(schema: dict) -> dict:
    """Replace the generic string schemas of the headers with the ones above."""
    for parameter in schema["paths"]["/process-payment"]["post"]["parameters"]:
        if parameter["in"] == "header" and parameter["name"] in HEADER_SCHEMAS:
            parameter["schema"] = HEADER_SCHEMAS[parameter["name"]]
    return schema


